package com.enzoftware.translatorapp.translate.data.local

import androidx.room3.RoomDatabase
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import androidx.sqlite.execSQL
import app.cash.turbine.test
import assertk.assertThat
import assertk.assertions.containsExactly
import assertk.assertions.isEmpty
import assertk.assertions.isEqualTo
import assertk.assertions.isFalse
import com.enzoftware.translatorapp.translate.data.history.RoomHistoryDataSource
import com.enzoftware.translatorapp.translate.domain.history.HistoryItem
import kotlinx.coroutines.test.runTest
import kotlin.coroutines.EmptyCoroutineContext
import kotlin.test.AfterTest
import kotlin.test.BeforeTest
import kotlin.test.Test

/**
 * Real Room + bundled SQLite behaviour, written once and run on every platform that can host the
 * native driver: iOS simulator (`iosTest`) and Android devices (`androidDeviceTest`).
 * The Android host JVM can't load the Android build of the bundled driver, so it has no subclass.
 */
abstract class HistoryDatabaseContract {

    /** A fresh in-memory database builder for each test. */
    abstract fun inMemoryDatabaseBuilder(): RoomDatabase.Builder<TranslatorDatabase>

    /** A legacy-database handle pointing at a scratch file that does not exist yet. */
    abstract fun scratchLegacyFile(): LegacyDatabaseFile

    private lateinit var database: TranslatorDatabase
    private lateinit var legacyFile: LegacyDatabaseFile

    @BeforeTest
    fun openDatabase() {
        database = inMemoryDatabaseBuilder().buildTranslatorDatabase()
        legacyFile = scratchLegacyFile()
        legacyFile.delete()
    }

    @AfterTest
    fun closeDatabase() {
        database.close()
        legacyFile.delete()
    }

    private val dao get() = database.historyDao()

    private fun importer() = LegacyHistoryImporter(BundledSQLiteDriver(), legacyFile, dao)

    /** Creates the file exactly as SQLDelight's `translate.sq` did, with the given rows. */
    private fun writeLegacyDatabase(vararg rows: HistoryEntity, createTable: Boolean = true) {
        BundledSQLiteDriver().open(legacyFile.path).use { connection ->
            if (!createTable) return@use
            connection.execSQL(
                """
                CREATE TABLE historyEntity(
                    id INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,
                    fromLanguageCode TEXT NOT NULL,
                    fromText TEXT NOT NULL,
                    toLanguage TEXT NOT NULL,
                    toText TEXT NOT NULL,
                    timestamp INTEGER NOT NULL
                )
                """.trimIndent(),
            )
            rows.forEach { row ->
                connection.prepare("INSERT INTO historyEntity VALUES (?, ?, ?, ?, ?, ?)").use { statement ->
                    statement.bindLong(1, row.id)
                    statement.bindText(2, row.fromLanguageCode)
                    statement.bindText(3, row.fromText)
                    statement.bindText(4, row.toLanguage)
                    statement.bindText(5, row.toText)
                    statement.bindLong(6, row.timestamp)
                    statement.step()
                }
            }
        }
    }

    private val hello = HistoryEntity(1, "en", "Hello", "es", "Hola", timestamp = 1_000)
    private val thanks = HistoryEntity(2, "en", "Thanks", "de", "Danke", timestamp = 2_000)

    @Test
    fun roomStoresHistoryNewestFirstAndReplacesById() = runTest {
        dao.upsert(hello)
        dao.upsert(thanks)
        dao.upsert(hello.copy(toText = "¡Hola!"))

        dao.observeHistory().test {
            assertThat(awaitItem()).containsExactly(thanks, hello.copy(toText = "¡Hola!"))
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun autoGeneratedIdsAreAssigned() = runTest {
        dao.upsert(hello.copy(id = 0))
        dao.upsert(thanks.copy(id = 0))

        dao.observeHistory().test {
            assertThat(awaitItem().map { it.id }.sorted()).containsExactly(1L, 2L)
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun legacySqlDelightHistoryIsImportedAndTheOldFileDeleted() = runTest {
        writeLegacyDatabase(hello, thanks)

        val source = RoomHistoryDataSource(dao, importer())
        source.getHistory(EmptyCoroutineContext).test {
            assertThat(awaitItem()).containsExactly(
                HistoryItem(2, "en", "Thanks", "de", "Danke"),
                HistoryItem(1, "en", "Hello", "es", "Hola"),
            )
            cancelAndIgnoreRemainingEvents()
        }
        assertThat(legacyFile.exists()).isFalse()
    }

    @Test
    fun anInterruptedImportCanRunAgainWithoutDuplicates() = runTest {
        writeLegacyDatabase(hello, thanks)
        dao.upsertAll(listOf(hello, thanks)) // rows copied, but the old file survived a crash

        importer().importIfPresent()

        dao.observeHistory().test {
            assertThat(awaitItem()).containsExactly(thanks, hello)
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun noLegacyFileImportsNothing() = runTest {
        importer().importIfPresent()

        dao.observeHistory().test {
            assertThat(awaitItem()).isEmpty()
            cancelAndIgnoreRemainingEvents()
        }
        assertThat(legacyFile.exists()).isFalse()
    }

    @Test
    fun aLegacyFileWithoutTheTableIsDiscarded() = runTest {
        writeLegacyDatabase(createTable = false)

        importer().importIfPresent()

        dao.observeHistory().test {
            assertThat(awaitItem().size).isEqualTo(0)
            cancelAndIgnoreRemainingEvents()
        }
        assertThat(legacyFile.exists()).isFalse()
    }
}
